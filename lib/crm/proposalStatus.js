// מצבי ההצעה במקום אחד.
//
// המודול הזה נטול תלויות בכוונה: גם החנות וגם מודול הזמנים מייבאים
// ממנו, ולכן אסור שהוא ייבא מהם בחזרה. החנות ממשיכה לייצא את הקבועים
// האלה כדי שכל הייבוא הקיים במערכת ימשיך לעבוד בדיוק כמו קודם.

export const PROPOSAL_STAGES = [
  "הוצע",
  "בבדיקה",
  "הוחלפו פרטים",
  "נפגשו",
  "בהמשך / מתקדמים",
  "אירוסין",
];

// ירד מהפרק: ההצעה נסגרה. עוברת להיסטוריה.
export const PROPOSAL_DROPPED = "ירד מהפרק";

// בהשהיה: מצב ביניים. ההצעה לא נסגרה, היא רק ממתינה - למשל כשאחד
// הצדדים בהפסקה. היא יורדת מהלוח הפעיל כדי לא להעמיס, נשמרת באזור
// "מוקפאים" ואפשר להחזיר אותה משם בלחיצה.
//
// חשוב: הצעה מוקפאת אינה נחשבת תהליך פעיל על המועמד/ת. היא מוסתרת
// מהפרופיל האישי, והמועמד/ת ממשיך/ה להיראות פנוי/ה לשאר הצוות כדי
// שיוכל/תוכל לקבל הצעות חדשות במקביל.
export const PROPOSAL_FROZEN = "בהשהיה";

export const isDroppedProposal = (proposal) => proposal?.status === PROPOSAL_DROPPED;
export const isFrozenProposal = (proposal) => proposal?.status === PROPOSAL_FROZEN;

// הצעה "חיה": לא נסגרה ולא מוקפאת. זו ההגדרה שקובעת מה מוצג בלוח
// הפעיל ומה נחשב תהליך פתוח על המועמד/ת.
export const isLiveProposal = (proposal) =>
  !isDroppedProposal(proposal) && !isFrozenProposal(proposal);
