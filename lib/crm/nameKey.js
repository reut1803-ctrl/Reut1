// מפתח חיפוש לפי שם, לשימוש בטופס ההרשמה החיצוני.
//
// למה בכלל מפתח ולא חיפוש רגיל: עמוד ההרשמה פתוח לכל אחד, בלי התחברות.
// אילו הוא היה מריץ שאילתת חיפוש על המאגר, כל מי שיש לו את הקישור היה יכול
// לסרוק ולשלוף את כל שמות המועמדים. במקום זה נבנה מסמך אחד לכל שם, שהמזהה
// שלו נגזר מהשם עצמו - וכך אפשר לבדוק שם מדויק אחד בלבד, בלי שום יכולת
// לעבור על הרשימה.

// אותיות סופיות מנורמלות לצורתן הרגילה, כדי ששינוי כתיב קל לא ימנע התאמה.
const FINALS = { "ך": "כ", "ם": "מ", "ן": "נ", "ף": "פ", "ץ": "צ" };

export function nameKey(name) {
  const raw = String(name || "").trim();
  if (!raw) return "";
  const cleaned = [...raw]
    // רק אותיות עבריות, אותיות לועזיות וספרות. רווחים, גרשיים ומקפים יורדים,
    // כך ש"בן-ציון", "בן ציון" ו"בן  ציון" מגיעים לאותו מפתח.
    .filter((ch) => /[א-ת0-9A-Za-z]/.test(ch))
    .map((ch) => FINALS[ch] || ch)
    .join("")
    .toLowerCase();
  // מזהה מסמך ב-Firestore אינו יכול להיות ריק, "." או ".."
  return cleaned.length >= 2 ? cleaned : "";
}
