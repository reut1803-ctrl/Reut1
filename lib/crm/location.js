// יישוב המגורים להצגה.
//
// לכל כרטיס יש שני שדות מיקום: אזור המגורים (למשל "יהודה"), שמשמש את
// מערך החיפוש והסינון, ויישוב המגורים עצמו (למשל "כרמי צור").
// בתצוגה למשפחות - בשורת התגיות בכרטיס, בקובץ ה-PDF ובטקסט השיתוף -
// מוצג היישוב המדויק, כי זו המידע שבאמת עוזר להחליט.
//
// האזור נשמר במלואו במאגר ואינו משתנה: הסינון לפי אזור ממשיך לעבוד
// בדיוק כשהיה. הוא משמש כאן רק כרשת ביטחון, לכרטיסים ותיקים שבהם
// היישוב טרם מולא - עדיף להציג אזור מאשר להשאיר שורה חסרה.
export function displayLocation(candidate) {
  const city = String(candidate?.city || "").trim();
  if (city) return city;
  return String(candidate?.region || "").trim();
}
