// --- תמחור לפי מסלול ---
export const CHABAD_TAG = 'חב"ד';
export const SUCCESS_FEE_CHABAD = 4000;
export const SUCCESS_FEE_GENERAL = 2500;

export function isChabadTrack(tag) {
  return String(tag || "").trim() === CHABAD_TAG;
}

// דמי ההצלחה לפי השיוך שנבחר בטופס. כל שיוך שאינו חב"ד הוא המסלול הכללי.
export function successFee(tag) {
  return isChabadTrack(tag) ? SUCCESS_FEE_CHABAD : SUCCESS_FEE_GENERAL;
}

// 2,500 / 4,000 - עם מפריד אלפים, כפי שזה נקרא בעברית
export function formatFee(amount) {
  return Number(amount || 0).toLocaleString("he-IL");
}

