// ניקוי טקסט לפני העתקה ללוח.
//
// הרקע: התווית "מהמעגל האישי · לא במאגר" היא סימון פנימי שנועד למסך בלבד -
// הוא אומר לצוות שלאדם הזה אין כרטיס במאגר. כשהתווית מגיעה גם לטקסט
// שנשלח למשפחה, מישהי צריכה למחוק אותה ידנית בכל פעם.
//
// הפונקציה מסירה את התווית מכל טקסט שמועתק, בכל וריאציות הפיסוק שבהן היא
// עשויה להופיע: בסוגריים או בלעדיהם, עם נקודה מפרידה, מקף, מקף ארוך או פסיק.
//
// חשוב: הרווחים שמסביב לתווית נבלעים אך ורק ברוחב השורה (רווח וטאב) ולא
// ירידות שורה. אחרת הסרת תווית שיושבת בשורה נפרדת הייתה מדביקה את השורה
// שלפניה לשורה שאחריה.
//
// הפונקציה אינה נוגעת בתצוגה: על המסך התווית ממשיכה להופיע כרגיל.
const H = "[ \\t]*"; // רווח אופקי בלבד
const SEPARATOR = `${H}[·\\-–—,:]?${H}`;
// מקדימים גם סימן הפרדה שלפני התווית ("שם - מהמעגל האישי..."),
// אחרת המקף היה נשאר תלוי באוויר בסוף השורה.
const MARKER = new RegExp(
  `${SEPARATOR}[\\(\\[]?${H}מהמעגל[ \\t]+האישי${SEPARATOR}לא[ \\t]+במאגר${H}[\\)\\]]?${H}`,
  "g"
);

export function cleanShareText(text) {
  if (!text) return "";
  return String(text)
    // מוחלפת ברווח בודד ולא בכלום, כדי שתווית שיושבת באמצע שורה
    // לא תדביק את המילים שלפניה לאלו שאחריה. רווח מיותר מצומצם בשלב הבא.
    .replace(MARKER, " ")
    .split("\n")
    .map((line) => line.replace(/[ \t]{2,}/g, " ").trimEnd())
    .join("\n")
    // שורה שכל תוכנה היה התווית הופכת לריקה. שלוש ירידות שורה ומעלה
    // מצטמצמות לשתיים, כדי שלא יישאר חלל באמצע הטקסט.
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}
